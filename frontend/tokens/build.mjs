#!/usr/bin/env node
// Generates the CSS custom properties and typed token map from tokens/tokens.json.
// No dependencies on purpose: the client team can read and own this in a minute.
import { readFileSync, writeFileSync, mkdirSync } from 'node:fs'
import { dirname, resolve } from 'node:path'
import { fileURLToPath } from 'node:url'

const root = resolve(dirname(fileURLToPath(import.meta.url)), '..')
const out = resolve(root, 'src/design-system/tokens')

export function loadTokens(path = resolve(root, 'tokens/tokens.json')) {
  return JSON.parse(readFileSync(path, 'utf8'))
}

const isLeaf = (v) => typeof v === 'string'

/** Flatten a nested object into [['a','b'], value] pairs. */
function flatten(obj, path = []) {
  return Object.entries(obj).flatMap(([k, v]) => (isLeaf(v) ? [[[...path, k], v]] : flatten(v, [...path, k])))
}

const lookup = (tokens, dotted) => dotted.split('.').reduce((o, k) => (o == null ? undefined : o[k]), tokens)

/** Replace {primitive.x.y} references; throws on a dangling reference. */
export function resolveRefs(tokens, value, where = '') {
  return value.replace(/\{([^}]+)\}/g, (_, ref) => {
    const hit = lookup(tokens, ref)
    if (!isLeaf(hit)) throw new Error(`Unresolved token reference {${ref}} ${where}`)
    return resolveRefs(tokens, hit, where)
  })
}

const cssName = (path) => `--ds-${path.join('-')}`

export function build(tokens) {
  const lines = (pairs) => pairs.map(([p, v]) => `  ${cssName(p)}: ${resolveRefs(tokens, v, cssName(p))};`)

  const primitives = flatten(tokens.primitive).map(([p, v]) => [p, v])
  const semantic = (mode) => flatten(tokens.semantic[mode])

  const css = `/* GENERATED by tokens/build.mjs from tokens/tokens.json. Do not edit by hand. */
:root {
  color-scheme: light;
${lines(primitives).join('\n')}

  /* semantic: light */
${lines(semantic('light')).join('\n')}
}

.app-dark {
  color-scheme: dark;
${lines(semantic('dark')).join('\n')}
}
`

  const resolved = (mode) => Object.fromEntries(semantic(mode).map(([p, v]) => [p.join('.'), resolveRefs(tokens, v)]))
  const names = semantic('light').map(([p]) => p.join('.'))
  const ts = `// GENERATED by tokens/build.mjs from tokens/tokens.json. Do not edit by hand.
export const semanticColors = {
  light: ${JSON.stringify(resolved('light'), null, 2).replace(/\n/g, '\n  ')},
  dark: ${JSON.stringify(resolved('dark'), null, 2).replace(/\n/g, '\n  ')},
} as const

export type SemanticColorToken = ${names.map((n) => `'${n}'`).join(' | ')}

export const primitives = ${JSON.stringify(Object.fromEntries(primitives.map(([p, v]) => [p.join('.'), resolveRefs(tokens, v)])), null, 2)} as const

/** CSS custom property for a semantic color token, e.g. cssVar('color.text.default') -> 'var(--ds-color-text-default)'. */
export const cssVar = (token: string): string => \`var(--ds-\${token.replace(/\\./g, '-')})\`
`
  return { css, ts }
}

if (process.argv[1] === fileURLToPath(import.meta.url)) {
  const { css, ts } = build(loadTokens())
  mkdirSync(out, { recursive: true })
  writeFileSync(resolve(out, 'tokens.css'), css)
  writeFileSync(resolve(out, 'tokens.ts'), ts)
  console.log('tokens: wrote src/design-system/tokens/tokens.css and tokens.ts')
}
